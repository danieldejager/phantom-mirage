#!/bin/sh
# pm-decoys-include: adds the include once, keeps a backup, creates the
# header only decoys.conf, refuses symlinks. Runs as any user.
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
s=$here/debian/scripts/pm-decoys-include
d=$(mktemp -d); trap 'rm -rf "$d"' EXIT
export PM_ETC="$d"
line="include /etc/phantom-mirage/decoys.conf"

# no main config: nothing to do, success
"$s" >/dev/null
[ ! -e "$d/decoys.conf" ]

printf 'create default\nset default default tcp action reset' > "$d/phantom-mirage.conf"
cp "$d/phantom-mirage.conf" "$d/orig"
"$s" >/dev/null
[ "$(grep -cxF "$line" "$d/phantom-mirage.conf")" = 1 ]
cmp "$d/orig" "$d/phantom-mirage.conf.pre-decoys.bak"
# the old last line without a newline is kept intact
grep -qx 'set default default tcp action reset' "$d/phantom-mirage.conf"
grep -q '^# Generated by pm-decoyd' "$d/decoys.conf"

# idempotent: second run changes nothing and keeps the first backup
cp "$d/phantom-mirage.conf" "$d/after1"
echo changed > "$d/decoys.conf"
"$s" >/dev/null
cmp "$d/after1" "$d/phantom-mirage.conf"
cmp "$d/orig" "$d/phantom-mirage.conf.pre-decoys.bak"
[ "$(cat "$d/decoys.conf")" = changed ]

# symlinked decoys.conf is refused
rm "$d/decoys.conf"; ln -s /etc/passwd "$d/decoys.conf"
if "$s" >/dev/null 2>&1; then echo "FAIL: symlink accepted"; exit 1; fi
echo "test_decoys_include: OK"
